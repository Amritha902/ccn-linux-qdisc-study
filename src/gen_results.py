#!/usr/bin/env python3
"""Generate the paper's results section from the measured data.

Emits paper/generated/results_body.tex containing the tables, the figure
includes and the quantitative statements. Prose that interprets the numbers
lives in paper/acape.tex; everything numeric is produced here so it cannot
drift from the logs.

Also emits a plain-text findings digest the author can read before writing
that prose.
"""
import argparse, glob, json, os, statistics as st, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from findings import welch, cohen_d          # noqa: E402
from analyse import load, system_key, ci95, DISPLAY, ORDER   # noqa: E402
from collections import defaultdict


def grouped(runs, wl):
    by = defaultdict(list)
    for r in runs:
        if r.get("workload") == wl:
            by[system_key(r)].append(r)
    return by


def fmt(v, nd=2):
    return "--" if v is None else f"{v:.{nd}f}"


def compare(by, lhs, rhs, metric):
    """Return (mean_lhs, mean_rhs, pct_change, p, dof) or None."""
    if lhs not in by or rhs not in by:
        return None
    A = [r.get(metric) for r in by[lhs]]
    B = [r.get(metric) for r in by[rhs]]
    a = [x for x in A if x is not None]
    b = [x for x in B if x is not None]
    if not a or not b:
        return None
    ma, mb = st.fmean(a), st.fmean(b)
    t, dof, p = welch(A, B)
    pct = (mb - ma) / ma * 100 if ma else float("nan")
    return ma, mb, pct, p, dof


HEADLINE = [
    ("sparse_rtt_p95_ms", "p95 RTT (probe)", 1),
    ("sparse_rtt_mean_ms", "mean RTT (probe)", 2),
    ("bulk_rtt_mean_ms", "mean RTT (bulk)", 2),
    ("backlog_mean_pkts", "mean backlog", 1),
    ("throughput_mbps", "goodput", 2),
    ("jain", "Jain", 4),
]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", default="results")
    ap.add_argument("--outdir", default="paper/generated")
    a = ap.parse_args()
    runs = load(a.results)
    os.makedirs(a.outdir, exist_ok=True)

    L = ["% GENERATED by src/gen_results.py -- do not edit by hand.", ""]
    digest = []

    for wl in ("steady", "staged"):
        by = grouped(runs, wl)
        if not by:
            continue
        nice = "steady" if wl == "steady" else "staged"
        L += [f"\\subsection{{{nice.capitalize()} workload}}", ""]
        L += ["\\begin{table}[h]", "\\centering", "\\scriptsize",
              f"\\caption{{All systems, {nice} workload "
              f"(mean $\\pm$ 95\\% CI over repetitions).}}",
              f"\\label{{tab:{wl}}}",
              f"\\input{{generated/table_{wl}}}", "\\end{table}", ""]
        for fig, cap in (
            (f"fig01_latency_tail_{wl}", "Tail latency across all systems (log scale)."),
            (f"fig02_latency_sparse_vs_bulk_{wl}",
             "Sparse probe flow versus bulk TCP flow RTT. The new-flow "
             "heuristic privileges the probe, so the two differ substantially."),
            (f"fig08_allparams_{wl}",
             "Every measured parameter against every system, normalised per "
             "row; cell values are the measured means."),
        ):
            L += ["\\begin{figure}[h]", "\\centering",
                  f"\\includegraphics[width=\\columnwidth]{{{fig}.png}}",
                  f"\\caption{{{cap}}}", f"\\label{{fig:{fig}}}",
                  "\\end{figure}", ""]

        # quantitative statements
        digest.append(f"\n{'='*78}\nWORKLOAD: {wl}\n{'='*78}")
        for lhs, rhs, label in (
            ("pfifo", "fq_codel", "unmanaged FIFO -> fq_codel"),
            ("fq_codel", "fq_codel_sham", "static -> sham controller (CPU cost only)"),
            ("fq_codel_sham", "fq_codel_acape", "sham -> ACAPE (control decisions only)"),
            ("fq_codel", "fq_codel_acape", "static -> ACAPE (combined)"),
            ("fq_codel", "cake", "fq_codel -> CAKE"),
            ("fq_codel", "pie", "fq_codel -> PIE (single queue)"),
        ):
            digest.append(f"\n  {label}   [{lhs} vs {rhs}]")
            for metric, name, nd in HEADLINE:
                c = compare(by, lhs, rhs, metric)
                if not c:
                    continue
                ma, mb, pct, p, dof = c
                verdict = ("n/a" if p is None else
                           ("DISTINGUISHABLE" if p < 0.05 else "not distinguishable"))
                digest.append(
                    f"    {name:22s} {fmt(ma,nd):>9s} -> {fmt(mb,nd):>9s}  "
                    f"({pct:+6.1f}%)  p={'%.3f'%p if p is not None else ' n/a'}  "
                    f"dof={('%.1f'%dof) if dof else ' n/a':>5s}  {verdict}")

    with open(os.path.join(a.outdir, "results_body.tex"), "w") as fh:
        fh.write("\n".join(L) + "\n")

    txt = "\n".join(digest)
    with open(os.path.join(a.outdir, "findings_digest.txt"), "w") as fh:
        fh.write(txt + "\n")
    print(txt)
    print(f"\nwrote {a.outdir}/results_body.tex and findings_digest.txt")


if __name__ == "__main__":
    main()
